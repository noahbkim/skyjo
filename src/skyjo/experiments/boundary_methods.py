def next_deal(scores: np.ndarray, starter: int, rng: random.Random) -> sj.Skyjo:
    """Reproduce start_next_round from its sufficient inputs, with no old board."""
    scores = np.asarray(scores)
    if (
        scores.ndim != 1
        or not 2 <= len(scores) <= sj.PLAYER_COUNT
        or not np.isfinite(scores).all()
        or (scores != np.floor(scores)).any()
        or (scores >= 100).any()
        or (scores < np.iinfo(np.int16).min).any()
        or not 0 <= starter < len(scores)
    ):
        raise ValueError("Expected nonterminal cumulative scores and a valid starter")
    state = sj.new(players=len(scores), rng=rng)
    state.game[sj.GAME_SCORES : sj.GAME_SCORES + len(scores)] = scores
    state.game[
        sj.GAME_LAST_REVEALED_TURNS : sj.GAME_LAST_REVEALED_TURNS + len(scores)
    ] = starter
    return sj.start_round(dataclasses.replace(state, turn=starter), rng=rng)


def next_deal_predictions(
    scores,
    starters,
    inference,
    *,
    sample_counts=(1, 10, 100),
    repeats=3,
    seed=20261006,
    batch_size=256,
    on_progress=None,
) -> tuple[dict[str, np.ndarray], dict[str, float]]:
    """Use nested sample streams, timing each budget independently.

    Outputs remain in next-starter order, matching score-model labels. Repeated
    deals use independent row/replicate streams, never the observed play seed.
    """
    scores, starters = np.asarray(scores), np.asarray(starters)
    if len(scores) != len(starters) or not len(scores):
        raise ValueError("Need matching nonempty scores and starters")
    if repeats < 1 or batch_size < 1 or not sample_counts or min(sample_counts) < 1:
        raise ValueError("Sample counts, repeats and batch size must be positive")
    results, timings = {}, {}
    for count in sample_counts:
        name = f"next_deal_{count}"
        values = np.empty((repeats, *scores.shape), dtype=np.float32)
        started = time.perf_counter()
        for repeat in range(repeats):
            # Bound construction memory as well as predictor tensor batch size.
            rows_per_batch = max(1, batch_size // count)
            for first in range(0, len(scores), rows_per_batch):
                last = min(first + rows_per_batch, len(scores))
                states = []
                for row in range(first, last):
                    sample_seed = int(
                        np.random.SeedSequence(
                            [seed, repeat, row, 0x4445414C]
                        ).generate_state(1, dtype=np.uint64)[0]
                    )
                    rng = random.Random(sample_seed)
                    states.extend(
                        next_deal(scores[row], int(starters[row]), rng)
                        for _ in range(count)
                    )
                predictions = np.asarray(
                    [
                        np.roll(prediction.value, -sj.get_player(state))
                        for state, prediction in zip(
                            states, inference.evaluate(states), strict=True
                        )
                    ]
                ).reshape(last - first, count, scores.shape[1])
                values[repeat, first:last] = predictions.mean(axis=1)
            if on_progress:
                on_progress(name, repeat + 1, time.perf_counter() - started)
        timings[name] = time.perf_counter() - started
        results[name] = values
    return results, timings


def _records(dataset, source_logs):
    expected = {source["path"]: source["sha256"] for source in dataset.sources}
    records = []
    for path in source_logs:
        content = Path(path).resolve().read_bytes()
        if hashlib.sha256(content).hexdigest() != expected[str(Path(path).resolve())]:
            raise ValueError("Source log changed after dataset construction")
        records.extend(
            json.loads(line) for line in content.splitlines() if line.strip()
        )
    return records


def validate_holdout(dataset, boundary_run, checkpoint_path, source_logs) -> dict:
    """Require later games generated by this checkpoint and no boundary-data overlap."""
    boundary_run, checkpoint_path = Path(boundary_run), Path(checkpoint_path).resolve()
    records = _records(dataset, source_logs)
    payload = decode_checkpoint(checkpoint_path)
    progress = payload["progress"]
    if any(
        row["game_index"] < progress["generated_games"]
        or row["iteration"] <= progress["iteration"]
        for row in records
    ):
        raise ValueError("Evaluation games must postdate the full model's training")
    if any(
        Path(row["checkpoint_path"]).resolve() != checkpoint_path for row in records
    ):
        raise ValueError(
            "Evaluation games must be generated by the evaluated checkpoint"
        )
    with np.load(boundary_run / "data/boundaries.npz", allow_pickle=False) as training:
        if np.intersect1d(dataset.game_ids, training["game_ids"]).size:
            raise ValueError("Evaluation games overlap the boundary model dataset")
    starters = {
        (
            json.dumps((row["run_id"], row["game_index"]), separators=(",", ":")),
            row["round_number"],
        ): row["ending_player"]
        for row in records
    }
    return {
        "full_model_progress": progress,
        "evaluation_game_index_min": min(row["game_index"] for row in records),
        "evaluation_game_index_max": max(row["game_index"] for row in records),
        "recorded_generator_matches_evaluator": True,
        "boundary_dataset_game_overlap": 0,
        "next_starters": [
            starters[(game_id, int(number))]
            for game_id, number in zip(
                dataset.game_ids, dataset.round_numbers, strict=True
            )
        ],
    }


def _write_json(path, data):
    Path(path).write_text(json.dumps(data, indent=2, allow_nan=False) + "\n")


def _summarize(predictions, timings, dataset, seed):
    models, errors = {}, {}
    for name, values in predictions.items():
        replicates = [
            boundary_value.probability_metrics(value, dataset.targets, dataset.scores)
            for value in values
        ]
        errors[name] = ((values.astype(np.float64) - dataset.targets) ** 2).mean(
            axis=(0, 2)
        )
        models[name] = {
            "replicates": replicates,
            "mean_metrics": {
                metric: float(np.mean([row[metric] for row in replicates]))
                for metric in ("value_mse", "brier_score", "cross_entropy", "ece")
            },
            "evaluation_seconds": timings[name],
            "milliseconds_per_boundary": 1000
            * timings[name]
            / (len(values) * len(dataset.scores)),
        }
    pairs = [(name, "next_deal_1") for name in models if name != "next_deal_1"]
    pairs += [(name, "next_deal_100") for name in models if name.startswith("score_")]
    comparisons = {
        f"{variant}_minus_{control}": paired_game_interval(
            errors[variant] - errors[control], dataset.game_ids, samples=2000, seed=seed
        )
        for variant, control in pairs
    }
    return {"methods": models, "paired_test_mse": comparisons}


def launch_comparison(
    source_logs,
    checkpoint_path,
    boundary_run,
    runs_dir=Path(".runs"),
    *,
    repeats=3,
    seed=20261006,
    batch_size=256,
    allow_dirty=False,
) -> Path:
    source_logs = [Path(path).resolve() for path in source_logs]
    checkpoint_path, boundary_run = (
        Path(checkpoint_path).resolve(),
        Path(boundary_run).resolve(),
    )
    if repeats < 1 or batch_size < 1:
        raise ValueError("repeats and batch_size must be positive")
    dataset = boundary_data.load_boundaries(source_logs)
    holdout = validate_holdout(dataset, boundary_run, checkpoint_path, source_logs)
    starters = np.asarray(holdout.pop("next_starters"), dtype=np.int64)
    boundary_results = json.loads((boundary_run / "results.json").read_text())
    config = {
        "name": "boundary-methods",
        "source_logs": list(map(str, source_logs)),
        "checkpoint": str(checkpoint_path),
        "boundary_run": str(boundary_run),
        "repeats": repeats,
        "seed": seed,
        "batch_size": batch_size,
        "sample_counts": [1, 10, 100],
        "holdout": holdout,
        "execution": {"device": "cpu", "threads": 1},
    }
    recorder = runs.RunRecorder.create(
        root=Path(runs_dir),
        repository=REPOSITORY,
        input_path=Path("comparison.json"),
        input_bytes=json.dumps(config).encode(),
        configuration=config,
        entrypoint="run_boundary_methods.py:compare",
        invocation=[arg for path in source_logs for arg in ("--round-log", str(path))]
        + [
            "--checkpoint",
            str(checkpoint_path),
            "--boundary-run",
            str(boundary_run),
            "--repeats",
            str(repeats),
            "--seed",
            str(seed),
            "--batch-size",
            str(batch_size),
            "--runs-dir",
            str(Path(runs_dir).resolve()),
            *(["--allow-dirty"] if allow_dirty else []),
        ],
        allow_dirty=allow_dirty,
    )
    previous_threads = torch.get_num_threads()
    with recorder, torch.random.fork_rng(devices=[]):
        try:
            torch.set_num_threads(1)
            print(f"Boundary comparison: {recorder.path}", flush=True)

            def artifact(path, kind):
                recorder.register_artifact(path, kind=kind, progress={})

            _write_json(recorder.path / "sources.json", dataset.sources)
            artifact(recorder.path / "sources.json", "source_provenance")
            np.savez_compressed(
                recorder.path / "data/boundaries.npz",
                scores=dataset.scores,
                targets=dataset.targets,
                game_ids=dataset.game_ids,
                round_numbers=dataset.round_numbers,
                iterations=dataset.iterations,
                starters=starters,
            )
            artifact(recorder.path / "data/boundaries.npz", "held_out_boundaries")
            shutil.copyfile(
                checkpoint_path, recorder.path / "checkpoints/full-game.pth"
            )
            artifact(
                recorder.path / "checkpoints/full-game.pth", "full_game_checkpoint"
            )
            sources = [
                REPOSITORY / "run_boundary_methods.py",
                *sorted((REPOSITORY / "src/skyjo").rglob("*.py")),
            ]
            for source in sources:
                destination = recorder.path / "source" / source.relative_to(REPOSITORY)
                destination.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(source, destination)
                artifact(destination, "experiment_source")
            inference = predictor.LocalPredictor(
                load_model(checkpoint_path), batch_size
            )
            inference.evaluate(
                [next_deal(dataset.scores[0], int(starters[0]), random.Random(seed))]
            )

            def progress(name, repeat, seconds):
                print(
                    f"{name} replicate {repeat}/{repeats}: {seconds:.1f}s", flush=True
                )
                recorder.record_event(
                    "deal_replicate",
                    context={"method": name, "repeat": repeat},
                    metrics={"seconds": seconds},
                )

            predictions, timings = next_deal_predictions(
                dataset.scores,
                starters,
                inference,
                repeats=repeats,
                seed=seed,
                batch_size=batch_size,
                on_progress=progress,
            )
            for kind in ("logistic", "mlp"):
                values, seconds = [], 0.0
                for entry in boundary_results["models"]:
                    if entry["kind"] != kind:
                        continue
                    path = boundary_run / entry["checkpoint"]
                    saved = torch.load(path, map_location="cpu", weights_only=True)
                    model = boundary_value.BoundaryValueModel(
                        kind, saved["players"], saved["hidden_width"]
                    )
                    model.load_state_dict(saved["model_state_dict"])
                    destination = (
                        recorder.path / "checkpoints" / f"{kind}-{entry['seed']}.pth"
                    )
                    shutil.copyfile(path, destination)
                    artifact(destination, "boundary_checkpoint")
                    started = time.perf_counter()
                    values.append(boundary_value.predict(model, dataset.scores))
                    seconds += time.perf_counter() - started
                if not values:
                    raise ValueError(f"No fitted {kind} models in boundary run")
                predictions[f"score_{kind}"] = np.asarray(values)
                timings[f"score_{kind}"] = seconds
            np.savez_compressed(recorder.path / "predictions.npz", **predictions)
            artifact(recorder.path / "predictions.npz", "valuation_predictions")
            report = {
                "dataset": dataset.summary,
                "holdout": holdout,
                **_summarize(predictions, timings, dataset, seed),
            }
            _write_json(recorder.path / "results.json", report)
            artifact(recorder.path / "results.json", "valuation_comparison")
            (recorder.path / "report.md").write_text(boundary_methods_report(report))
            artifact(recorder.path / "report.md", "experiment_report")
        finally:
            torch.set_num_threads(previous_threads)
    return recorder.path
